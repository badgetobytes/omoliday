// Regenerates Countries.js from a saved copy of Nager.Date's country list.
//
//   node scripts/generate-countries.mjs tests/fixture-countries.json > Countries.js
//
// Refresh the snapshot by saving https://date.nager.at/api/v3/AvailableCountries
// over tests/fixture-countries.json first. The script itself never touches the
// network: it reads the JSON file given as its only argument and prints the
// module, sorted by country code so the output is stable for a given input.
import { readFileSync } from "node:fs";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/generate-countries.mjs <AvailableCountries.json>");
  process.exit(2);
}

const list = JSON.parse(readFileSync(source, "utf8"));
if (!Array.isArray(list)) throw new Error("expected a JSON array");

const rows = list
  .map((entry) => [String(entry.countryCode || ""), String(entry.name || "")])
  .filter(([code, name]) => /^[A-Z]{2}$/.test(code) && name !== "")
  .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const lines = [
  "// Countries the Nager.Date public-holiday API covers, as ISO 3166-1 alpha-2",
  "// codes with an English name for the panel. Generated by",
  "// scripts/generate-countries.mjs from the /api/v3/AvailableCountries",
  "// snapshot in tests/fixture-countries.json; regenerate rather than edit.",
  "// Plain ES5 so it loads unchanged in the shell's QML engine and under",
  "// node for the tests.",
  "",
  "var COUNTRIES = [",
  ...rows.map(([code, name], i) => `  [${JSON.stringify(code)}, ${JSON.stringify(name)}]${i < rows.length - 1 ? "," : ""}`),
  "]",
  "",
  "var index = null",
  "",
  "function lookup() {",
  "  if (index === null) {",
  "    index = {}",
  "    for (var i = 0; i < COUNTRIES.length; i++) index[COUNTRIES[i][0]] = COUNTRIES[i][1]",
  "  }",
  "  return index",
  "}",
  "",
  "function isSupported(code) {",
  "  return Object.prototype.hasOwnProperty.call(lookup(), String(code))",
  "}",
  "",
  "function name(code) {",
  "  var table = lookup()",
  "  var key = String(code)",
  "  return Object.prototype.hasOwnProperty.call(table, key) ? table[key] : \"\"",
  "}",
  "",
  "if (typeof module !== \"undefined\") {",
  "  module.exports = { COUNTRIES: COUNTRIES, isSupported: isSupported, name: name }",
  "}",
  "",
];
process.stdout.write(lines.join("\n"));
